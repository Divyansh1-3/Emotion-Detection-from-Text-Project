"""Load the small trained model and predict an emotion for English text."""

import gzip
import pickle
import re
from functools import lru_cache
from pathlib import Path

MODEL_PATH = Path(__file__).resolve().parent / "model" / "emotion_model.pkl.gz"
MAX_CHARACTERS = 1000
EMOTIONS = ("anger", "fear", "joy", "love", "sadness", "surprise")


def validate_text(text):
    """Reject empty input, very long input, and non-English scripts."""
    if not isinstance(text, str) or not text.strip():
        raise ValueError("Please enter an English sentence first.")
    text = text.strip()
    if len(text) > MAX_CHARACTERS:
        raise ValueError(f"Please keep your text under {MAX_CHARACTERS + 1} characters.")
    if any(letter.isalpha() and not letter.isascii() for letter in text):
        raise ValueError("Please use English text with English letters only.")
    if not re.search(r"[A-Za-z]{2,}", text):
        raise ValueError("Please enter English words, not just numbers or symbols.")
    return text


@lru_cache(maxsize=1)
def load_model():
    """Read our bundled model once. No training or downloads when the app opens."""
    # Only load this project's model, generated by train_model.py.
    with gzip.open(MODEL_PATH, "rb") as model_file:
        return pickle.load(model_file)


def predict_emotion(text):
    text = validate_text(text)
    model = load_model()
    features = model.named_steps["tfidf"].transform([text])
    if features.nnz == 0:
        raise ValueError("I could not recognise those words. Try a short English sentence.")

    classifier = model.named_steps["classifier"]
    probabilities = classifier.predict_proba(features)[0]
    scores = dict(zip(classifier.classes_, map(float, probabilities)))
    ranked = sorted(scores, key=scores.get, reverse=True)
    best, second = ranked[:2]
    # Positive TF-IDF x coefficient contributions explain this model's choice.
    class_index = list(classifier.classes_).index(best)
    names = model.named_steps["tfidf"].get_feature_names_out()
    contributions = features.data * classifier.coef_[class_index, features.indices]
    ordered = sorted(zip(features.indices, contributions), key=lambda item: item[1], reverse=True)
    keywords = []
    used_words = set()
    for feature_index, contribution in ordered:
        phrase = str(names[feature_index])
        words = set(phrase.split())
        if contribution > 0 and not words.intersection(used_words):
            keywords.append(phrase)
            used_words.update(words)
        if len(keywords) == 3:
            break
    return {
        "emotion": best,
        "score": scores[best],
        "scores": scores,
        "uncertain": scores[best] < 0.45 or scores[best] - scores[second] < 0.10,
        "keywords": keywords,
        "runner_up": second,
    }
